                            <p>A stroke occurs when the blood supply to part of the brain is interrupted or reduced, preventing brain tissue from getting oxygen and nutrients. Brain cells begin to die in minutes. It is a medical emergency, and prompt treatment is crucial. Early action can reduce brain damage and other complications.</p>
                            <p>The process of stroke rehabilitation is crucial for complete recovery of the patient, it is provided over a stipulated period of time. The goal of stroke rehabilitation is to help the patient relearn the skills lost by the stroke affected part of the brain and hence help the patient regain independence and improve quality of life.</p>
                            <p>The duration of stroke rehabilitation depends on the severity of the stroke and related complications. Some stroke survivors recover quickly while others require some form of long-term stroke rehabilitation, lasting possibly months or years after the stroke.</p>
